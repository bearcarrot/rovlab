function LegalLayout({
  title,
  intro,
  updated,
  children,
}: {
  title: string;
  intro?: string;
  updated?: boolean;
  children: ReactNode;
}) {
  return (
    <article className="mx-auto max-w-3xl space-y-4">
      <header className="space-y-1">
        <h1 className="font-display text-xl font-semibold">{title}</h1>
        {intro && <p className="text-sm text-text-muted">{intro}</p>}
        {updated && <p className="text-xs text-text-faint">ปรับปรุงล่าสุด: {LEGAL_UPDATED}</p>}
      </header>
      {children}
    </article>
  );
}

function Section({ title, children }: { title: string; children: ReactNode }) {
  return (
    <section className="space-y-2 rounded-card border border-border bg-bg-surface p-4 shadow-card">
      <h2 className="font-display text-base font-semibold">{title}</h2>
      <div className="space-y-2 text-sm leading-relaxed text-text-muted">{children}</div>
    </section>
  );
}

function Bullets({ items }: { items: string[] }) {
  return (
    <ul className="list-disc space-y-1 pl-5">
      {items.map((t) => (
        <li key={t}>{t}</li>
      ))}
    </ul>
  );
}

